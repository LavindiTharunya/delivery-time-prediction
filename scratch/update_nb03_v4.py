    "test_df['distance_km'] = test_df['distance_km'].fillna(dist_med)\n",
    "\n",
    "train_df['total_weight_g'] = train_df['total_weight_g'].fillna(weight_med)\n",
    "test_df['total_weight_g'] = test_df['total_weight_g'].fillna(weight_med)\n",
    "\n",
    "# Seller dispatch lookup\n",
    "seller_dispatch_lookup = train_df.groupby('seller_id')['seller_dispatch_days'].median()\n",
    "train_df['seller_avg_dispatch_days'] = train_df['seller_id'].map(seller_dispatch_lookup).fillna(global_dispatch_med)\n",
    "test_df['seller_avg_dispatch_days'] = test_df['seller_id'].map(seller_dispatch_lookup).fillna(global_dispatch_med)\n",
    "\n",
    "# Seller delivery days lookup\n",
    "seller_perf_lookup = train_df.groupby('seller_id')['delivery_days'].mean()\n",
